/**
 * Build `lib/client.js` — the browser-half bundle the client module system
 * serves for `exports["./client"]`.
 *
 * The browser half owns no React component, no CSS module and no platform
 * request, so a bundler would only add a toolchain. What the module loader
 * actually needs is one script that registers a factory:
 *
 *   window.__ModuleLoader__.load({ id, factory: (require) => exports })
 *
 * and the `id` **must equal the npm package name**, or the client half stays
 * silently dead (dsh-plugin-dev §1). This script transpiles each
 * `src/client/*.ts`, strips the relative imports (their bodies are concatenated
 * in dependency order), drops module-level `export` keywords, and wraps the
 * result in that contract. Run it after editing any client source.
 */
import { createRequire } from 'node:module'
import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = dirname(dirname(fileURLToPath(import.meta.url)))
const srcDir = join(root, 'src', 'client')
const outFile = join(root, 'lib', 'client.js')
const packageName = JSON.parse(await readFile(join(root, 'package.json'), 'utf8')).name

/** Concatenation order: leaf modules first, entry last. */
const MODULES = ['constants.ts', 'locales.ts', 'fold.ts', 'settings-card.ts', 'index.ts']

/**
 * Shared modules the host's module table serves into every browser half.
 *
 * `react` is the one this plugin needs: a slot component must return a React
 * element. Everything in `@deepseek-ai/dsh-*` stays forbidden — the vendor rule
 * forbids loading host packages (`dsh-client-ui-primitives` included), and the
 * shipped bundles are not a plugin's API surface.
 */
const SHARED_ALLOWED = new Set(['react', 'react-dom', 'react/jsx-runtime', 'react-dom/client', 'cordis', '@deepseek-ai/cordis'])

/**
 * Load the TypeScript compiler. A local install wins; `DSH_TYPESCRIPT` may point
 * at a module directory elsewhere (the arrangement used across this plugin family,
 * so a repo can build without vendoring a 60 MB devDependency).
 */
function loadTypeScript() {
  const require = createRequire(import.meta.url)
  for (const candidate of ['typescript', process.env.DSH_TYPESCRIPT, join(root, '..', 'dsh-arrowkey-nav', 'node_modules', 'typescript')]) {
    if (candidate === undefined || candidate === '') continue
    try {
      return require(candidate)
    } catch {
      // Try the next candidate.
    }
  }
  throw new Error('typescript not found: add it as a devDependency, or set DSH_TYPESCRIPT=<module dir>')
}

/** Drop relative imports: those modules are concatenated into this bundle. */
function stripRelativeImports(code) {
  return code
    .split('\n')
    .filter((line) => !/^\s*import\b[^;]*from\s+['"]\.\/[^'"]+['"];?\s*$/.test(line))
    .filter((line) => !/^\s*import\s+['"]\.\/[^'"]+['"];?\s*$/.test(line))
    .join('\n')
}

/**
 * Drop module-level `export` keywords: every module shares one factory closure,
 * so only the entry's `apply`/`inject` are exported at the end.
 */
function stripExportKeywords(code) {
  return code
    .split('\n')
    .map((line) => line.replace(/^(\s*)export\s+(?=(?:const|let|var|function|class|async)\b)/, '$1'))
    .map((line) => line.replace(/^(\s*)export\s+default\s+/, '$1'))
    .join('\n')
}

/** Transpile one TypeScript module to erasable JavaScript. */
function transpile(ts, fileName, source) {
  const result = ts.transpileModule(source, {
    fileName,
    compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ESNext, removeComments: false },
  })
  return stripExportKeywords(stripRelativeImports(result.outputText)).trim()
}

/** Wrap the transpiled modules in the module-loader contract. */
function composeBundle(parts) {
  return [
    `// ${packageName} — browser half (client module-loader bundle).`,
    '// Generated by scripts/build-client.mjs from src/client/*.ts; edit the sources, not this file.',
    'window.__ModuleLoader__.load({',
    `  id: ${JSON.stringify(packageName)},`,
    '  factory: (require) => {',
    '    const module = { exports: {} };',
    '    const exports = module.exports;',
    ...parts.map((part) => part.replace(/^(?=.)/gm, '    ')),
    '    exports.inject = inject;',
    '    exports.apply = apply;',
    '    return module.exports;',
    '  },',
    '});',
    '',
  ].join('\n')
}

const ts = loadTypeScript()
const parts = []
for (const name of MODULES) {
  parts.push(transpile(ts, name, await readFile(join(srcDir, name), 'utf8')))
}

const bundle = composeBundle(parts)

// --- bundle gates -----------------------------------------------------------
if (!bundle.startsWith(`window.__ModuleLoader__.load({`) && !bundle.includes('window.__ModuleLoader__.load({')) {
  throw new Error('bundle must register through window.__ModuleLoader__.load')
}
if (!bundle.includes(`id: ${JSON.stringify(packageName)}`)) {
  throw new Error(`bundle id must equal the package name (${packageName})`)
}
if (!bundle.includes('exports.apply = apply;') || !bundle.includes('exports.inject = inject;')) {
  throw new Error('bundle must export apply and inject')
}
const requests = [...bundle.matchAll(/\brequire\(\s*['"]([^'"]+)['"]\s*\)/g)].map((m) => m[1])
const illegal = requests.filter((id) => !SHARED_ALLOWED.has(id))
if (illegal.length > 0) {
  throw new Error(`bundle may only require shared modules (${[...SHARED_ALLOWED].join(', ')}), found: ${illegal.join(', ')}`)
}

await mkdir(dirname(outFile), { recursive: true })
await writeFile(outFile, bundle, 'utf8')
console.log(`wrote ${outFile} (${bundle.length} chars, ${parts.length} modules)`)
